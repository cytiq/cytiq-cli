#!/usr/bin/env Rscript
# Regenerate the R reference values embedded in Rust unit tests.
# Usage: R_LIBS_USER=parity/.env/Rlib Rscript parity/make_fixtures.R
# Writes data/fixtures/peacoqc/{density,smooth_spline}_reference.rs and
# data/fixtures/transform/flowcore_reference.rs.

num <- function(v) {
  s <- sprintf("%.17g", v)
  ifelse(grepl("[.eEn]", s), s, paste0(s, ".0"))
}
arr <- function(name, v) sprintf("const %s: [f64; %d] = [%s];\n", name, length(v), paste(num(v), collapse = ", "))
pairs <- function(name, idx, v) sprintf("const %s: [(usize, f64); %d] = [%s];\n", name, length(idx),
                                        paste(sprintf("(%d, %s)", idx, num(v[idx + 1])), collapse = ", "))

out <- file("data/fixtures/peacoqc/density_reference.rs", "w")
x <- c(1, 2, 2.5, 3, 7, 8, 8.2, 9)
d <- density(x)
cat("// Generated by parity/make_fixtures.R with", R.version.string, "\n", file = out)
cat("// stats::density(c(1, 2, 2.5, 3, 7, 8, 8.2, 9)) and bw.nrd0 of the same data.\n", file = out)
cat(sprintf("const R_BW: f64 = %s;\n", num(bw.nrd0(x))), file = out)
cat(pairs("R_X", c(0, 255, 511), d$x), file = out)
cat(pairs("R_Y", c(0, 99, 255, 399, 511), d$y), file = out)
close(out)

out <- file("data/fixtures/peacoqc/smooth_spline_reference.rs", "w")
y1 <- c(1.2, 1.5, 1.1, 1.9, 2.4, 2.2, 3.1, 2.8, 2.5, 4.0, 3.6, 3.3)
set.seed(7)
y2 <- round(sin(seq_len(130) / 9) + rnorm(130, sd = 0.3), 6)
cat("// Generated by parity/make_fixtures.R with", R.version.string, "\n", file = out)
cat("// stats::smooth.spline(seq_along(y), y, spar = 0.5)$y\n", file = out)
cat(arr("SHORT_Y", y1), file = out)
cat(arr("SHORT_FIT", smooth.spline(seq_along(y1), y1, spar = 0.5)$y), file = out)
cat(arr("LONG_Y", y2), file = out)
cat(arr("LONG_FIT", smooth.spline(seq_along(y2), y2, spar = 0.5)$y), file = out)
close(out)

suppressPackageStartupMessages(library(flowCore))
dir.create("data/fixtures/transform", showWarnings = FALSE)
out <- file("data/fixtures/transform/flowcore_reference.rs", "w")
x <- c(-10000, -1000, -100, -10, -1, 0, 1, 10, 100, 1000, 10000, 1e5, 262144)
channels <- c(0, 10, 57, 100, 128, 200, 256)
lg <- logicleTransform(w = 0.5, t = 262144, m = 4.5, a = 0)
hl <- eval(hyperlogtGml2(parameters = "X", T = 262144, M = 4.5, W = 0.5, A = 0))
b256 <- flowWorkspace::flowjo_biexp(channelRange = 256, maxValue = 262144, pos = 4.418539922, neg = 0, widthBasis = -100)
b256i <- flowWorkspace::flowjo_biexp(channelRange = 256, maxValue = 262144, pos = 4.418539922, neg = 0, widthBasis = -100, inverse = TRUE)
b4096 <- flowWorkspace::flowjo_biexp(channelRange = 4096, maxValue = 262144, pos = 4.5, neg = 0, widthBasis = -10)
cat("// Generated by parity/make_fixtures.R with", R.version.string, "\n", file = out)
cat("// flowCore", as.character(packageVersion("flowCore")), "/ flowWorkspace", as.character(packageVersion("flowWorkspace")), "\n", file = out)
cat(arr("R_INPUT", x), file = out)
cat(arr("R_LOGICLE", lg(x)), file = out)
cat(arr("R_HYPERLOG", as.numeric(hl(matrix(x, ncol = 1, dimnames = list(NULL, "X"))))), file = out)
cat(arr("R_BIEXP_256", b256(x)), file = out)
cat(arr("R_CHANNELS", channels), file = out)
cat(arr("R_BIEXP_256_INVERSE", b256i(channels)), file = out)
cat(arr("R_BIEXP_4096", b4096(x)), file = out)
close(out)

# ---- cytoscan: upstream CytoScan building blocks
suppressPackageStartupMessages({ library(flowFP); library(mclust); library(transport) })
dir.create("data/fixtures/cytoscan", showWarnings = FALSE)
mat <- function(name, m) sprintf("const %s: [[f64; %d]; %d] = [%s];\n", name, ncol(m), nrow(m),
                                 paste(apply(m, 1, function(r) paste0("[", paste(num(r), collapse = ", "), "]")),
                                       collapse = ", "))
out <- file("data/fixtures/cytoscan/reference.rs", "w")
cat("// Generated by parity/make_fixtures.R with", R.version.string, "\n", file = out)
cat("// transport", as.character(packageVersion("transport")), "/ flowFP", as.character(packageVersion("flowFP")),
    "/ mclust", as.character(packageVersion("mclust")), "\n", file = out)

# transport::wasserstein1d (CytoScan EMD)
set.seed(3)
w_a <- round(rnorm(7), 4); w_b <- round(rnorm(5, 1), 4)
cat(arr("EMD_A", w_a), arr("EMD_B", w_b), file = out)
cat(sprintf("const EMD_EXPECTED: f64 = %s;\n", num(wasserstein1d(w_a, w_b))), file = out)

# CytoScan::calculateBins: table(cut(x, breaks = quantile(agg, 0:10/10)))
set.seed(4)
b_agg <- round(rnorm(200), 4)
b_x <- c(min(b_agg), max(b_agg) + 1, min(b_agg) - 1, round(rnorm(37, 0.3), 4))
breaks <- quantile(b_agg, probs = seq(0, 1, by = 0.1))
counts <- as.numeric(table(cut(b_x, breaks = breaks)))
cat(arr("BIN_AGGREGATE", b_agg), arr("BIN_VALUES", b_x), arr("BIN_EXPECTED", counts / sum(counts)), file = out)

# flowFP::flowFPModel(nRecursions = 4) + flowFP() bin frequencies
set.seed(5)
fp_agg <- cbind(round(rnorm(300), 4), round(rnorm(300, 2, 3), 4), round(rexp(300), 4))
colnames(fp_agg) <- c("A", "B", "C")
fp_x <- fp_agg[sample(300, 60), ] + 0.25
model <- flowFPModel(flowCore::flowFrame(fp_agg), parameters = colnames(fp_agg), nRecursions = 4)
fp_counts <- counts(flowFP(flowCore::flowFrame(fp_x), model))
cat(mat("FINGERPRINT_AGGREGATE", fp_agg), mat("FINGERPRINT_VALUES", fp_x),
    arr("FINGERPRINT_EXPECTED", as.numeric(fp_counts / sum(fp_counts))), file = out)

# mclust::Mclust(modelNames = "VVV") on one cluster (XXX)
set.seed(11)
g_a <- MASS::mvrnorm(120, c(0, 0, 0), matrix(c(1, .5, .2, .5, 1, .3, .2, .3, 1), 3))
g_b <- MASS::mvrnorm(80, c(5, 4, -3), diag(c(.5, .8, .3)))
g_x <- round(rbind(g_a, g_b), 6)
g1 <- Mclust(g_x[1:120, ], modelNames = "VVV", verbose = FALSE)
cat(mat("GMM_POINTS", g_x), file = out)
cat(sprintf("const GMM_ONE_G: usize = %d;\nconst GMM_ONE_LOGLIK: f64 = %s;\n", g1$G, num(g1$loglik)), file = out)
cat(sprintf("const GMM_ONE_MODEL: &str = \"%s\";\n", g1$modelName), file = out)
cat(arr("GMM_ONE_LOG_DENSITY", log(dens(g_x[1:120, ], g1$modelName, parameters = g1$parameters))), file = out)

# mclust::Mclust defaults (CytoScan's novelty model): the BIC table of every
# structure cytiq fits, the chosen model and its log-densities.
# - GMM_POINTS (n > d), initialised from hc(modelName = "EII", use = "SVD")
#   as cytiq does; Mclust's own default for n > d starts from hcVVV.
# - WIDE_POINTS (n <= d), where Mclust itself starts from hcEII and only
#   tries spherical and diagonal structures.
opt <- function(v) ifelse(is.na(v), "None", paste0("Some(", num(v), ")"))
bic_table <- function(name, b, models) {
  m <- b[, models, drop = FALSE]
  sprintf("const %s: [[Option<f64>; %d]; %d] = [%s];\n", name, ncol(m), nrow(m),
          paste(apply(m, 1, function(r) paste0("[", paste(opt(r), collapse = ", "), "]")), collapse = ", "))
}
mixture_fixture <- function(prefix, x, fit, models) {
  cat(sprintf("const %s_MODEL: &str = \"%s\";\nconst %s_G: usize = %d;\nconst %s_BIC: f64 = %s;\nconst %s_LOGLIK: f64 = %s;\n",
              prefix, fit$modelName, prefix, fit$G, prefix, num(fit$bic), prefix, num(fit$loglik)), file = out)
  cat(bic_table(paste0(prefix, "_BIC_TABLE"), fit$BIC, models), file = out)
  cat(arr(paste0(prefix, "_LOG_DENSITY"), log(dens(x, fit$modelName, parameters = fit$parameters))), file = out)
}
all_models <- c("EII", "VII", "EEI", "VEI", "EVI", "VVI", "EEE", "VVV")
g_hc <- hc(g_x, modelName = "EII", use = "SVD")
g_default <- Mclust(g_x, initialization = list(hcPairs = g_hc), verbose = FALSE)
mixture_fixture("GMM_DEFAULT", g_x, g_default, all_models)
set.seed(13)
w_centres <- rbind(rep(0, 20), c(rep(3, 10), rep(0, 10)), c(rep(0, 10), rep(-3, 10)))
w_x <- round(do.call(rbind, lapply(1:3, function(k)
  matrix(rnorm(5 * 20, mean = rep(w_centres[k, ], each = 5), sd = c(1, 0.5, 2)[k]), 5))), 6)
w_fit <- Mclust(w_x, verbose = FALSE)
cat(mat("WIDE_POINTS", w_x), file = out)
mixture_fixture("WIDE", w_x, w_fit, all_models[1:6])
w_classes <- hclass(hc(w_x, modelName = "EII", use = "SVD"), 2:9)
cat(sprintf("const WIDE_HCLASS: [[usize; 8]; %d] = [%s];\n", nrow(w_classes),
            paste(apply(w_classes - 1, 1, function(r) paste0("[", paste(r, collapse = ", "), "]")), collapse = ", ")),
    file = out)

# isotree::isolation.forest(sample_size = 1, ntrees = 1000, ndim = 1) scores
set.seed(12)
i_x <- round(rbind(matrix(rnorm(19 * 4), 19), c(4, -4, 3, 5)), 6)
forest <- isotree::isolation.forest(i_x, sample_size = 1, ntrees = 1000, ndim = 1, seed = 42, nthreads = 1)
cat(mat("ISOTREE_POINTS", i_x), arr("ISOTREE_SCORES", predict(forest, i_x)), file = out)
close(out)
