#!/usr/bin/env Rscript
# Regenerate the R reference values embedded in Rust unit tests.
# Usage: R_LIBS_USER=parity/.env/Rlib Rscript parity/make_fixtures.R
# Writes data/fixtures/peacoqc/{density,smooth_spline}_reference.rs and
# data/fixtures/transform/flowcore_reference.rs.

num <- function(v) {
  s <- sprintf("%.17g", v)
  ifelse(grepl("[.eEn]", s), s, paste0(s, ".0"))
}
arr <- function(name, v) sprintf("const %s: [f64; %d] = [%s];\n", name, length(v), paste(num(v), collapse = ", "))
pairs <- function(name, idx, v) sprintf("const %s: [(usize, f64); %d] = [%s];\n", name, length(idx),
                                        paste(sprintf("(%d, %s)", idx, num(v[idx + 1])), collapse = ", "))

out <- file("data/fixtures/peacoqc/density_reference.rs", "w")
x <- c(1, 2, 2.5, 3, 7, 8, 8.2, 9)
d <- density(x)
cat("// Generated by parity/make_fixtures.R with", R.version.string, "\n", file = out)
cat("// stats::density(c(1, 2, 2.5, 3, 7, 8, 8.2, 9)) and bw.nrd0 of the same data.\n", file = out)
cat(sprintf("const R_BW: f64 = %s;\n", num(bw.nrd0(x))), file = out)
cat(pairs("R_X", c(0, 255, 511), d$x), file = out)
cat(pairs("R_Y", c(0, 99, 255, 399, 511), d$y), file = out)
close(out)

out <- file("data/fixtures/peacoqc/smooth_spline_reference.rs", "w")
y1 <- c(1.2, 1.5, 1.1, 1.9, 2.4, 2.2, 3.1, 2.8, 2.5, 4.0, 3.6, 3.3)
set.seed(7)
y2 <- round(sin(seq_len(130) / 9) + rnorm(130, sd = 0.3), 6)
cat("// Generated by parity/make_fixtures.R with", R.version.string, "\n", file = out)
cat("// stats::smooth.spline(seq_along(y), y, spar = 0.5)$y\n", file = out)
cat(arr("SHORT_Y", y1), file = out)
cat(arr("SHORT_FIT", smooth.spline(seq_along(y1), y1, spar = 0.5)$y), file = out)
cat(arr("LONG_Y", y2), file = out)
cat(arr("LONG_FIT", smooth.spline(seq_along(y2), y2, spar = 0.5)$y), file = out)
close(out)

suppressPackageStartupMessages(library(flowCore))
dir.create("data/fixtures/transform", showWarnings = FALSE)
out <- file("data/fixtures/transform/flowcore_reference.rs", "w")
x <- c(-10000, -1000, -100, -10, -1, 0, 1, 10, 100, 1000, 10000, 1e5, 262144)
channels <- c(0, 10, 57, 100, 128, 200, 256)
lg <- logicleTransform(w = 0.5, t = 262144, m = 4.5, a = 0)
hl <- eval(hyperlogtGml2(parameters = "X", T = 262144, M = 4.5, W = 0.5, A = 0))
b256 <- flowWorkspace::flowjo_biexp(channelRange = 256, maxValue = 262144, pos = 4.418539922, neg = 0, widthBasis = -100)
b256i <- flowWorkspace::flowjo_biexp(channelRange = 256, maxValue = 262144, pos = 4.418539922, neg = 0, widthBasis = -100, inverse = TRUE)
b4096 <- flowWorkspace::flowjo_biexp(channelRange = 4096, maxValue = 262144, pos = 4.5, neg = 0, widthBasis = -10)
cat("// Generated by parity/make_fixtures.R with", R.version.string, "\n", file = out)
cat("// flowCore", as.character(packageVersion("flowCore")), "/ flowWorkspace", as.character(packageVersion("flowWorkspace")), "\n", file = out)
cat(arr("R_INPUT", x), file = out)
cat(arr("R_LOGICLE", lg(x)), file = out)
cat(arr("R_HYPERLOG", as.numeric(hl(matrix(x, ncol = 1, dimnames = list(NULL, "X"))))), file = out)
cat(arr("R_BIEXP_256", b256(x)), file = out)
cat(arr("R_CHANNELS", channels), file = out)
cat(arr("R_BIEXP_256_INVERSE", b256i(channels)), file = out)
cat(arr("R_BIEXP_4096", b4096(x)), file = out)
close(out)
